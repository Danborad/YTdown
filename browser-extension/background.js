const SUPPORTED_DOMAINS = [
    'youtube.com',
    'google.com',
    'accounts.google.com',
    'bilibili.com',
    'vimeo.com',
    'tiktok.com',
    'twitter.com',
    'x.com',
    'instagram.com',
    'behance.net',
    'adobe.com'
];

const DEFAULT_STATE = {
    serverBase: 'http://127.0.0.1:38491/api/cookie-sync',
    serverBases: [
        'http://127.0.0.1:38491/api/cookie-sync',
        'http://127.0.0.1:38492/api/cookie-sync',
        'http://127.0.0.1:38493/api/cookie-sync',
        'http://127.0.0.1:38494/api/cookie-sync',
        'http://127.0.0.1:38495/api/cookie-sync'
    ],
    token: '',
    paired: false,
    browserName: '',
    lastSyncAt: '',
    lastError: '',
    lastCount: 0,
    lastMode: '',
    lastOutputPath: '',
    activePort: 38491,
    statusText: '未连接下载器'
};

const FALLBACK_DOWNLOAD_FILENAME = 'YT下载器 Cookie Sync/browser_extension_cookies.txt';

function getBrowserName() {
    return navigator.userAgent.includes('Edg/') ? 'Edge' : 'Chrome';
}

async function getState() {
    const stored = await chrome.storage.local.get(DEFAULT_STATE);
    return {
        ...DEFAULT_STATE,
        ...stored,
        browserName: stored.browserName || getBrowserName()
    };
}

async function setState(patch) {
    await chrome.storage.local.set(patch);
    return getState();
}

function getServerBases(state) {
    const candidates = Array.isArray(state.serverBases) && state.serverBases.length > 0
        ? state.serverBases
        : DEFAULT_STATE.serverBases;
    const ordered = [];
    const primary = state.serverBase || DEFAULT_STATE.serverBase;

    if (primary) ordered.push(primary);
    candidates.forEach((item) => {
        if (item && !ordered.includes(item)) ordered.push(item);
    });

    return ordered;
}

function extractPortFromBase(serverBase) {
    try {
        return Number(new URL(serverBase).port || 38491);
    } catch (error) {
        return 38491;
    }
}

function buildNetscapeCookieFile(cookies) {
    const lines = ['# Netscape HTTP Cookie File', '# Generated by YT下载器 Browser Extension', ''];

    cookies.forEach((cookie) => {
        if (!cookie || !cookie.domain || !cookie.name) return;

        let domain = String(cookie.domain).trim();
        const hostOnly = Boolean(cookie.hostOnly);
        if (hostOnly) {
            domain = domain.replace(/^\./, '');
        } else if (!domain.startsWith('.')) {
            domain = `.${domain}`;
        }

        const includeSubdomains = hostOnly ? 'FALSE' : 'TRUE';
        const cookiePath = cookie.path || '/';
        const secure = cookie.secure ? 'TRUE' : 'FALSE';
        const expires = cookie.session || !cookie.expirationDate ? 0 : Math.floor(cookie.expirationDate);
        const name = String(cookie.name);
        const value = String(cookie.value || '');

        lines.push(`${domain}\t${includeSubdomains}\t${cookiePath}\t${secure}\t${expires}\t${name}\t${value}`);
    });

    return lines.join('\n');
}

async function downloadFallbackCookieFile(cookies) {
    const content = buildNetscapeCookieFile(cookies);
    const dataUrl = `data:text/plain;charset=utf-8,${encodeURIComponent(content)}`;

    await chrome.downloads.download({
        url: dataUrl,
        filename: FALLBACK_DOWNLOAD_FILENAME,
        conflictAction: 'overwrite',
        saveAs: false
    });

    return {
        success: true,
        cookieCount: cookies.length,
        outputPath: FALLBACK_DOWNLOAD_FILENAME,
        mode: 'folder-fallback'
    };
}

function matchesSupportedDomain(domain) {
    const normalized = String(domain || '').replace(/^\./, '');
    return SUPPORTED_DOMAINS.some((item) => normalized === item || normalized.endsWith(`.${item}`));
}

async function collectCookies() {
    const cookieMap = new Map();

    for (const domain of SUPPORTED_DOMAINS) {
        const cookies = await chrome.cookies.getAll({ domain });
        cookies.forEach((cookie) => {
            const key = [cookie.domain, cookie.path, cookie.name, cookie.storeId || '0'].join('|');
            if (!cookieMap.has(key)) {
                cookieMap.set(key, {
                    domain: cookie.domain,
                    hostOnly: cookie.hostOnly,
                    path: cookie.path,
                    secure: cookie.secure,
                    session: cookie.session,
                    expirationDate: cookie.expirationDate || 0,
                    name: cookie.name,
                    value: cookie.value
                });
            }
        });
    }

    return Array.from(cookieMap.values()).sort((a, b) => {
        const left = `${a.domain}|${a.name}|${a.path}`;
        const right = `${b.domain}|${b.name}|${b.path}`;
        return left.localeCompare(right);
    });
}

async function postJson(path, payload) {
    const state = await getState();
    const serverBases = getServerBases(state);
    let lastError = null;

    for (const serverBase of serverBases) {
        try {
            const response = await fetch(`${serverBase}${path}`, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify(payload)
            });

            const result = await response.json().catch(() => ({ success: false, message: '本地服务返回异常' }));
            if (!response.ok || !result.success) {
                throw new Error(result.message || `请求失败 (${response.status})`);
            }

            await setState({
                serverBase,
                activePort: extractPortFromBase(serverBase),
                lastError: ''
            });

            return result;
        } catch (error) {
            lastError = error;
        }
    }

    throw new Error(lastError?.message || '无法连接本地下载器');
}

async function pairWithDownloader(token) {
    const formattedToken = String(token || '').trim().toUpperCase();
    if (!formattedToken) {
        throw new Error('请输入配对码');
    }

    const browserName = getBrowserName();
    const result = await postJson('/pair', {
        token: formattedToken,
        browserName,
        extensionVersion: chrome.runtime.getManifest().version
    });

    await setState({
        token: formattedToken,
        paired: true,
        browserName,
        lastError: '',
        lastMode: 'local-api',
        statusText: '已连接下载器'
    });

    return result;
}

async function syncCookies(reason = 'manual') {
    const state = await getState();
    const formattedToken = String(state.token || '').trim().toUpperCase();
    if (!formattedToken) {
        throw new Error('请先输入配对码');
    }

    const cookies = await collectCookies();
    const browserName = getBrowserName();
    let result;

    try {
        result = await postJson('/sync', {
            token: formattedToken,
            browserName,
            reason,
            cookies,
            extensionVersion: chrome.runtime.getManifest().version
        });
    } catch (error) {
        result = await downloadFallbackCookieFile(cookies).catch(() => {
            throw error;
        });
    }

    const cookieCount = result.cookieCount || cookies.length;
    const lastMode = result.mode || 'local-api';

    await setState({
        paired: true,
        browserName,
        lastSyncAt: new Date().toISOString(),
        lastCount: cookieCount,
        lastMode,
        lastOutputPath: result.outputPath || '',
        lastError: '',
        statusText: lastMode === 'folder-fallback'
            ? `已写入兜底目录 ${cookieCount} 个 Cookie`
            : `已同步 ${cookieCount} 个 Cookie`
    });

    return result;
}

async function connectAndSync(token) {
    await pairWithDownloader(token);
    return syncCookies('pair');
}

function queueSync(delayMs = 3000) {
    chrome.alarms.create('downloader-pro-cookie-sync', { when: Date.now() + delayMs });
}

chrome.runtime.onInstalled.addListener(async () => {
    await setState({ browserName: getBrowserName() });
    chrome.alarms.create('downloader-pro-cookie-sync-heartbeat', { periodInMinutes: 15 });
});

chrome.runtime.onStartup.addListener(async () => {
    await setState({ browserName: getBrowserName() });
    const state = await getState();
    if (state.paired && state.token) {
        queueSync(5000);
    }
});

chrome.cookies.onChanged.addListener(async (changeInfo) => {
    const state = await getState();
    if (!state.paired || !state.token) return;
    if (!matchesSupportedDomain(changeInfo.cookie?.domain)) return;
    queueSync(2500);
});

chrome.alarms.onAlarm.addListener(async (alarm) => {
    if (!['downloader-pro-cookie-sync', 'downloader-pro-cookie-sync-heartbeat'].includes(alarm.name)) {
        return;
    }

    const state = await getState();
    if (!state.paired || !state.token) return;

    try {
        await syncCookies(alarm.name === 'downloader-pro-cookie-sync' ? 'change' : 'heartbeat');
    } catch (error) {
        await setState({
            lastError: error.message,
            statusText: '同步失败'
        });
    }
});

chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
    (async () => {
        if (message?.type === 'get-state') {
            sendResponse({ success: true, state: await getState() });
            return;
        }

        if (message?.type === 'connect') {
            const result = await connectAndSync(message.token);
            sendResponse({ success: true, result, state: await getState() });
            return;
        }

        if (message?.type === 'sync-now') {
            const result = await syncCookies('manual');
            sendResponse({ success: true, result, state: await getState() });
            return;
        }

        if (message?.type === 'save-token') {
            await setState({ token: String(message.token || '').trim().toUpperCase() });
            sendResponse({ success: true, state: await getState() });
            return;
        }

        sendResponse({ success: false, message: '未知指令' });
    })().catch(async (error) => {
        await setState({
            lastError: error.message,
            statusText: '同步失败'
        });
        sendResponse({ success: false, message: error.message, state: await getState() });
    });

    return true;
});
